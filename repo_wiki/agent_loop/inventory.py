def stack_facts(repo: RepoView) -> dict[str, Any]:
    manifests: list[str] = []
    entries: list[str] = []
    tree: dict[str, int] = {}
    for rel in repo.files():
        name = rel.rsplit("/", 1)[-1]
        if name in MANIFESTS and rel.count("/") <= 2:
            dep_lines = []
            for i, ln in enumerate(repo.lines(rel) or [], 1):
                s = ln.strip()
                if not s or s.startswith(("#", "//")):
                    continue
                if name == "package.json" and not re.match(
                    r'"[@\w./-]+"\s*:\s*"[~^<>=*\w.\-: /]+"', s
                ):
                    continue
                if name == "go.mod" and not (
                    s.startswith(("require", "module")) or re.match(r"[\w.-]+\.[\w./-]+ v", s)
                ):
                    continue
                dep_lines.append(f"{rel}:{i}: {s[:140]}")
            manifests.extend(dep_lines[:80])
        if name in ENTRY_NAMES or re.match(r"cmd/[^/]+/main\.go$", rel):
            entries.append(rel)
        top = rel.split("/", 1)[0] if "/" in rel else "."
        tree[top] = tree.get(top, 0) + 1
    return {
        "manifest_lines": manifests[:200],
        "entry_like_files": entries[:40],
        "top_level": dict(sorted(tree.items())),
    }


