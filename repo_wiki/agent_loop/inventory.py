"""Deterministic, repo-agnostic inventories, outlines and shard plans (no LLM).

Inventory items are hints AND accounting obligations: each must end up cited by a verified fact /
route or dismissed with a vetted reason. Shards carry compact line-numbered outlines rather than
whole files so large repositories stay within small per-agent contexts.
"""

from __future__ import annotations

import re
from collections import defaultdict
from collections.abc import Callable, Iterable
from typing import Any

from repo_wiki.agent_loop.repo import RepoView

Item = dict[str, Any]

SRC_EXT = (
    ".py",
    ".go",
    ".js",
    ".ts",
    ".mjs",
    ".cjs",
    ".jsx",
    ".tsx",
    ".java",
    ".kt",
    ".rb",
    ".php",
    ".rs",
    ".cs",
    ".vue",
)
TEST_RX = re.compile(
    r"(^|/)(tests?|__tests__|spec|testdata|fixtures?|examples?|e2e)/|_test\.\w+$|(^|/)test_[^/]+$"
    r"|\.(spec|test)\.\w+$|conftest\.py$"
)
WRAPPERS = frozenset(
    {
        "src",
        "app",
        "lib",
        "internal",
        "pkg",
        "cmd",
        "packages",
        "apps",
        "services",
        "server",
        "source",
    }
)
DOC_DIRS = frozenset(
    {
        "docs",
        "doc",
        "documentation",
        "snapshots",
        "screenshots",
        "assets",
        "images",
        ".github",
        "scripts",
    }
)
GEN_RX = re.compile(r"(?i)code generated|do not edit|autogenerated|auto-generated|@generated")


def is_src(rel: str) -> bool:
    return rel.endswith(SRC_EXT) and not TEST_RX.search(rel)


def top_dirs(repo: RepoView) -> list[str]:
    return sorted({f.split("/", 1)[0] for f in repo.files() if "/" in f and not f.startswith(".")})


def files_under(repo: RepoView, d: str) -> list[str]:
    return [f for f in repo.files() if f.startswith(d.rstrip("/") + "/")]


def chunk(items: list[Any], size_of: Callable[[Any], int], max_lines: int = 240) -> list[list[Any]]:
    shards: list[list[Any]] = []
    cur: list[Any] = []
    n = 0
    for it in items:
        s = size_of(it)
        if cur and n + s > max_lines:
            shards.append(cur)
            cur, n = [], 0
        cur.append(it)
        n += s
    if cur:
        shards.append(cur)
    return shards


def is_generated(repo: RepoView, rel: str) -> bool:
    if re.search(r"\.pb\.\w+$|_pb2\.py$|\.gen\.\w+$|\.min\.js$", rel):
        return True
    return any(GEN_RX.search(ln) for ln in (repo.lines(rel) or [])[:5])


def _representative(repo: RepoView, files: Iterable[str]) -> list[str]:
    return sorted(
        files,
        key=lambda f: (
            is_generated(repo, f),
            TEST_RX.search(f) is not None,
            not is_src(f),
            f.count("/"),
            -len(repo.lines(f) or []),
        ),
    )


# ------------------------------------------------------------------ overview
def overview_inventory(repo: RepoView) -> dict[str, list[Item]]:
    """modules: depth-1 dirs with files (+ depth-2 children of wrapper dirs); entries: main-like."""
    mods: list[Item] = []
    allf = repo.files()
    for d in top_dirs(repo):
        fs = [f for f in allf if f.startswith(d + "/")]
        if not fs:
            continue
        kids = sorted({f.split("/")[1] for f in fs if f.count("/") >= 2})
        if d in WRAPPERS and len(kids) >= 2:
            for k in kids:
                sub = [f for f in fs if f.startswith(f"{d}/{k}/")]
                if any(is_src(f) or f.endswith((".sql", ".yml", ".yaml")) for f in sub):
                    mods.append({"key": f"{d}/{k}", "n_files": len(sub), "oblig": True})
            root_src = [f for f in fs if f.count("/") == 1 and is_src(f)]
            if root_src:
                names = ", ".join(x.split("/")[-1] for x in root_src[:6])
                mods.append(
                    {
                        "key": f"{d}/ (root files: {names})",
                        "path": d,
                        "n_files": len(root_src),
                        "oblig": True,
                    }
                )
        else:
            src = [f for f in fs if is_src(f)]
            mods.append(
                {
                    "key": d,
                    "n_files": len(fs),
                    "oblig": bool(src)
                    or d in ("migrations", "db", "config", "static", "web", "test", "tests"),
                    "doc_only": d.lower() in DOC_DIRS,
                }
            )
    root_src = [f for f in allf if "/" not in f and is_src(f)]
    if root_src:
        more = "…" if len(root_src) > 8 else ""
        mods.append(
            {
                "key": f". (root source files: {', '.join(root_src[:8])}{more})",
                "path": ".",
                "n_files": len(root_src),
                "oblig": True,
            }
        )
    entry_rx: list[tuple[re.Pattern[str], tuple[str, ...]]] = [
        (re.compile(r"^func main\(\)"), (".go",)),
        (re.compile(r"""^if __name__ == ["']__main__["']"""), (".py",)),
        (re.compile(r"\.listen\(|createServer\("), (".js", ".ts", ".mjs")),
        (
            re.compile(r"^\s*(app|application|server)\s*=\s*\w*(FastAPI|Flask|Express|express)\("),
            (".py",),
        ),
        (re.compile(r"=\s*(get_application|create_app)\(\)"), (".py",)),
    ]
    entries: list[Item] = []
    for f in allf:
        if TEST_RX.search(f):
            continue
        for rx, exts in entry_rx:
            if not f.endswith(exts):
                continue
            for i, ln in enumerate(repo.lines(f) or [], 1):
                if rx.search(ln):
                    entries.append({"file": f, "line": i, "text": ln.strip()[:160]})
                    break
    for f in allf:
        if f.endswith("package.json") and f.count("/") <= 1:
            for i, ln in enumerate(repo.lines(f) or [], 1):
                if re.match(r'\s*"(main|bin|start)"\s*:', ln):
                    entries.append({"file": f, "line": i, "text": ln.strip()[:160]})
    seen: set[str] = set()
    ent: list[Item] = []
    for e in entries:
        if e["file"] not in seen:
            seen.add(e["file"])
            ent.append(e)
    return {"modules": mods, "entries": ent[:30]}


def module_path(mod: Item) -> str:
    return str(mod.get("path", mod["key"]) if "(" in mod["key"] else mod["key"])


def module_head(repo: RepoView, mod_path: str, n_files: int = 2, n_lines: int = 30) -> str:
    """Numbered head of the most representative hand-written files inside a module."""
    if mod_path == ".":
        fs = [f for f in repo.files() if "/" not in f]
    else:
        fs = files_under(repo, mod_path)
    out = []
    for f in _representative(repo, fs)[:n_files]:
        ls = repo.lines(f) or []
        body = "\n".join(
            f"{i}: {ls[i - 1].rstrip()[:150]}"
            for i in range(1, min(len(ls), n_lines) + 1)
            if ls[i - 1].strip()
        )
        out.append(f"== {f} ({len(ls)} lines)\n{body}")
    return "\n".join(out)


_DECL_RX = re.compile(
    r"^\s*(//\s*Package|package |func [A-Z]|type [A-Z]\w* (struct|interface)|class \w|"
    r"def [a-z]\w*\(|async def|module\.exports|export (default|const|function|class)|router\.|"
    r"app\.(use|get|post)|\"\"\"|#\s+\w)"
)


def module_outline(repo: RepoView, mod: Item, cap: int = 26) -> str:
    d = str(mod.get("path", mod["key"]))
    if d == ".":
        fs = [f for f in repo.files() if "/" not in f and is_src(f)]
    elif "(" in mod["key"]:
        fs = [f for f in repo.files() if f.startswith(d + "/") and f.count("/") == d.count("/") + 1]
    else:
        fs = files_under(repo, d)
    listed = ", ".join(x[len(d) + 1 :] if d != "." else x for x in fs[:14])
    lines = [f"## module {mod['key']} — {len(fs)} files: {listed}" + (" …" if len(fs) > 14 else "")]
    for f in _representative(repo, fs)[:3]:
        ls = repo.lines(f) or []
        hits = [i for i, ln in enumerate(ls, 1) if _DECL_RX.match(ln)][:6]
        if len(hits) < 3:
            head = [i for i, ln in enumerate(ls[:40], 1) if ln.strip()][:5]
            hits = sorted(set(hits) | set(head))[:8]
        if hits:
            lines.append(f"  {f}: " + " | ".join(f"{i}: {ls[i - 1].strip()[:90]}" for i in hits))
    return "\n".join(lines[:cap])


def identity_outline(repo: RepoView) -> str:
    out = []
    readme = next((f for f in repo.files() if re.match(r"(?i)readme(\.\w+)?$", f)), None)
    if readme:
        ls = repo.lines(readme) or []
        keep = [
            i for i, ln in enumerate(ls[:400], 1) if ln.strip() and (i <= 14 or ln.startswith("#"))
        ][:45]
        out.append(
            f"== {readme} (head + headings)\n" + "\n".join(f"{i}: {ls[i - 1][:160]}" for i in keep)
        )
    manifests = (
        "package.json",
        "pyproject.toml",
        "go.mod",
        "setup.py",
        "setup.cfg",
        "requirements.txt",
        "Cargo.toml",
        "pom.xml",
    )
    for f in repo.files():
        if "/" not in f and f in manifests:
            ls = repo.lines(f) or []
            body = "\n".join(f"{i}: {ln[:140]}" for i, ln in enumerate(ls[:120], 1) if ln.strip())
            out.append(f"== {f}\n{body}")
    return "\n\n".join(out)


# ------------------------------------------------------------------ install
CMD_START = re.compile(
    r"^\s*(\$\s*)?(git|make|docker|docker-compose|podman|podman-compose|go|npm|npx|yarn|pnpm|pip|"
    r"pip3|python|python3|poetry|uv|uvicorn|gunicorn|flask|alembic|cp|mv|touch|echo|export|cd|curl|"
    r"wget|open|createdb|mysql|psql|cargo|mvn|gradle|java|node|pm2|kubectl|helm|bash|sh|\./)\b"
)


def doc_files(repo: RepoView) -> list[str]:
    rx = re.compile(
        r"(?i)(readme[^/]*|quickstart[^/]*|install[^/]*|getting[_-]?started[^/]*|setup[^/]*|"
        r"deploy[^/]*)\.(md|rst|txt)$"
    )
    fs = [f for f in repo.files() if "/" not in f and rx.match(f)]
    main = [f for f in fs if re.match(r"(?i)readme\.(md|rst|txt)$", f)]
    return main + [f for f in fs if f not in main]


def doc_commands(repo: RepoView, rel: str) -> list[Item]:
    ls = repo.lines(rel) or []
    cmds: list[Item] = []
    in_code = rst_block = False
    for i, ln in enumerate(ls, 1):
        s = ln.strip()
        if s.startswith("```"):
            in_code = not in_code
            continue
        if rel.endswith(".rst"):
            if s.endswith("::"):
                rst_block = True
                continue
            if rst_block and s and not ln.startswith((" ", "\t")):
                rst_block = False
        if (in_code or rst_block or ln.startswith("    ")) and CMD_START.match(s):
            cmds.append({"file": rel, "line": i, "text": s[:200], "kind": "doc_cmd"})
    return cmds


def build_inventory(repo: RepoView) -> list[Item]:
    items: list[Item] = []
    for f in repo.files():
        name = f.rsplit("/", 1)[-1]
        depth = f.count("/")
        if (name == "Makefile" and depth == 0) or (f.endswith(".mk") and depth <= 1):
            ls = repo.lines(f) or []
            for i, ln in enumerate(ls, 1):
                m = re.match(r"^([A-Za-z0-9_.\-]+)\s*:(?!=)", ln)
                if m and not ln.startswith((".PHONY", "\t")):
                    nxt = ls[i] if i < len(ls) else ""
                    text = (ln.strip() + "  ⟶ " + nxt.strip())[:200]
                    items.append({"file": f, "line": i, "text": text, "kind": "make"})
        elif name == "package.json" and depth == 0:
            in_s = False
            for i, ln in enumerate(repo.lines(f) or [], 1):
                if re.match(r'\s*"(scripts|engines)"\s*:', ln):
                    in_s = True
                    items.append({"file": f, "line": i, "text": ln.strip(), "kind": "pkg"})
                    continue
                if in_s:
                    if ln.strip().startswith("}"):
                        in_s = False
                        continue
                    items.append({"file": f, "line": i, "text": ln.strip()[:200], "kind": "pkg"})
        elif name.startswith("Dockerfile") and depth <= 2:
            for i, ln in enumerate(repo.lines(f) or [], 1):
                if re.match(
                    r"^\s*(FROM|EXPOSE|CMD|ENTRYPOINT|RUN (pip|poetry|yarn|npm|go build))\b", ln
                ):
                    items.append({"file": f, "line": i, "text": ln.strip()[:200], "kind": "docker"})
        elif re.match(r"(docker|podman)-compose[^/]*\.ya?ml$|compose\.ya?ml$", name) and depth == 0:
            for i, ln in enumerate(repo.lines(f) or [], 1):
                if re.match(r"^  [\w.-]+:\s*$", ln) or re.search(
                    r"\b(image|command|ports?):|^\s*-\s*['\"]?[\w${}:.-]*\d+:\d+", ln
                ):
                    items.append(
                        {"file": f, "line": i, "text": ln.rstrip()[:200], "kind": "compose"}
                    )
        elif name == "go.mod" and depth == 0:
            for i, ln in enumerate(repo.lines(f) or [], 1):
                if re.match(r"^(go|toolchain)\s", ln):
                    items.append({"file": f, "line": i, "text": ln.strip(), "kind": "runtime"})
        elif name == "pyproject.toml" and depth == 0:
            for i, ln in enumerate(repo.lines(f) or [], 1):
                if re.match(r"^\s*python\s*=|^requires-python|^\[tool\.poetry\.scripts\]", ln):
                    items.append({"file": f, "line": i, "text": ln.strip(), "kind": "runtime"})
    return items


ENV_RX = re.compile(
    r"""(?:getenv|Getenv|LookupEnv|environ(?:\.get)?|env\.get)\s*[\[(]\s*["']([A-Z][A-Z0-9_]{2,})["']"""
    r"""|process\.env\.([A-Z][A-Z0-9_]{2,})|\benv:"([A-Z][A-Z0-9_]{2,})|^\s*([A-Z][A-Z0-9_]{2,}):\s*Joi\."""
)
ENV_NAME_RX = re.compile(r"\b[A-Z][A-Z0-9]*_[A-Z0-9_]+\b|\b[A-Z]{3,}\b")


def config_inventory(repo: RepoView) -> list[Item]:
    items: list[Item] = []
    seen: set[tuple[str, str]] = set()
    for f in repo.files():
        name = f.rsplit("/", 1)[-1]
        if name.startswith(".env") and f.count("/") == 0:
            # only reachable when the security deny globs allow it (e.g. a template env file)
            for i, ln in enumerate(repo.lines(f) or [], 1):
                m = re.match(r"^\s*([A-Z][A-Z0-9_]+)=", ln)
                if m:
                    items.append(
                        {
                            "file": f,
                            "line": i,
                            "text": ln.strip()[:160],
                            "key": m.group(1),
                            "kind": "dotenv",
                        }
                    )
        elif is_src(f):
            for i, ln in enumerate(repo.lines(f) or [], 1):
                for m in ENV_RX.finditer(ln):
                    k = next(g for g in m.groups() if g)
                    if (k, f) not in seen:
                        seen.add((k, f))
                        items.append(
                            {
                                "file": f,
                                "line": i,
                                "text": ln.strip()[:160],
                                "key": k,
                                "kind": "env",
                            }
                        )
    port_rx = re.compile(r"(?i)(listen|port|addr)\w*\W{1,6}[\"'`]?[\w.]*:?\d{4,5}\b")
    for f in repo.files():
        if is_src(f) or (
            re.search(r"(^|/)config[^/]*\.(ya?ml|json|toml)$", f) and f.count("/") <= 1
        ):
            for i, ln in enumerate(repo.lines(f) or [], 1):
                if port_rx.search(ln) and not ln.strip().startswith(("//", "#")) and len(ln) < 220:
                    items.append(
                        {
                            "file": f,
                            "line": i,
                            "text": ln.strip()[:160],
                            "key": None,
                            "kind": "default",
                        }
                    )
    return items


# ------------------------------------------------------------------ reader essentials
_START_RX = re.compile(
    r"(?i)\b(start|run|up|serve|server|daemon|dev)\b|^\./|uvicorn|gunicorn|flask run|manage\.py runserver"
)
MIGRATE_RX = re.compile(
    r"(?i)\bmigrat\w*|\balembic\b[^\n]*\bupgrade\b|\bdb:(?:migrate|push)\b|\bprisma\s+(?:migrate|db\s+push)"
    r"|\bflyway\b|\bliquibase\b|\bgoose\b[^\n]*\bup\b|\bsyncdb\b"
)
DEV_RX = re.compile(r"(?i)\b(?:yarn|pnpm|bun)\s+(?:run\s+)?dev\b|\bnpm\s+run\s+dev\b|\bmake\s+dev\b")
_ENV_TEMPLATE_RX = re.compile(r"^\.env\.(example|sample|template|dist|tpl|default)$")


def compose_env_files(repo: RepoView) -> list[Item]:
    """``env_file:`` entries of the root compose files (the env file a reader must provide)."""
    items: list[Item] = []
    for f in repo.files():
        name = f.rsplit("/", 1)[-1]
        if f.count("/") or not re.match(r"(docker|podman)-compose[^/]*\.ya?ml$|compose\.ya?ml$", name):
            continue
        ls = repo.lines(f) or []
        for i, ln in enumerate(ls, 1):
            m = re.match(r"^\s*env_file\s*:\s*(.*)$", ln)
            if not m:
                continue
            vals = [m.group(1).strip()] if m.group(1).strip() else []
            for nxt in ls[i : i + 5]:
                mm = re.match(r"^\s*-\s*(\S+)", nxt)
                if not mm:
                    break
                vals.append(mm.group(1))
            text = f"env_file: {' '.join(v.strip('\'\"') for v in vals)}".strip()
            items.append({"file": f, "line": i, "text": text[:160], "kind": "env_file"})
    return items


def reader_essentials(repo: RepoView) -> dict[str, list[Item]]:
    """What a reader needs to get the project running, when the repository has it: the env file
    it must provide, the default listen port, and a start command. Deterministic; the install
    page must establish each present kind with a verified fact."""
    env: list[Item] = compose_env_files(repo)
    for f in repo.files():
        if f.count("/") == 0 and _ENV_TEMPLATE_RX.match(f):
            env.append({"file": f, "line": 1, "text": f"{f} (template env file)", "kind": "env_file"})
    for f in repo.files():
        if not is_src(f) or TEST_RX.search(f):
            continue
        for i, ln in enumerate(repo.lines(f) or [], 1):
            if re.search(r"load_dotenv\(|dotenv\.config\(|require\(['\"]dotenv['\"]\)|env_file\s*=\s*['\"]\.env", ln):
                env.append({"file": f, "line": i, "text": ln.strip()[:160], "kind": "env_file"})
                break
    docs = doc_files(repo)[:3]
    cmds = [c for d in docs for c in doc_commands(repo, d)]
    env += [c for c in cmds if re.search(r"(^|[\s/])\.env\b", c["text"])]
    port = [c for c in config_inventory(repo) if c["kind"] == "default"]
    build = build_inventory(repo)
    port += [
        x
        for x in build
        if (x["kind"] == "compose" and re.search(r"\d+:\d+", x["text"]))
        or (x["kind"] == "docker" and re.match(r"\s*EXPOSE\b", x["text"]))
    ]
    start = [c for c in cmds if _START_RX.search(c["text"])]
    start += [
        x
        for x in build
        if (x["kind"] == "make" and _START_RX.search(x["text"].split(":", 1)[0]))
        or (x["kind"] == "pkg" and re.match(r'\s*"(start|dev|serve)"\s*:', x["text"]))
        or (x["kind"] == "docker" and re.match(r"\s*(CMD|ENTRYPOINT)\b", x["text"]))
        or (x["kind"] == "compose" and re.search(r"\bcommand:", x["text"]))
    ]
    # database preparation the reader must run (migrations), wherever the repo states it
    migrate = [c for c in cmds if MIGRATE_RX.search(c["text"])]
    migrate += [
        x
        for x in build
        if MIGRATE_RX.search(x["text"])
        and (
            x["kind"] in ("make", "pkg")
            or (x["kind"] == "docker" and re.match(r"\s*(CMD|ENTRYPOINT|RUN)\b", x["text"]))
            or (x["kind"] == "compose" and re.search(r"\bcommand:", x["text"]))
        )
    ]
    # the development start script a reader uses locally (package "dev" script, documented `yarn dev`)
    dev = [c for c in cmds if DEV_RX.search(c["text"])]
    dev += [x for x in build if x["kind"] == "pkg" and re.match(r'\s*"dev"\s*:', x["text"])]
    return {"env_file": env, "port": port, "start": start, "migrate": migrate, "dev": dev}


# ------------------------------------------------------------------ data model
DM_RX: list[tuple[str, re.Pattern[str], tuple[str, ...]]] = [
    ("ddl", re.compile(r"(?i)^\s*CREATE\s+TABLE\s+(IF\s+NOT\s+EXISTS\s+)?[`\"]?(\w+)"), (".sql",)),
    ("alembic", re.compile(r"""op\.create_table\(\s*$|op\.create_table\(\s*["'](\w+)"""), (".py",)),
    (
        "orm",
        re.compile(
            r"""__tablename__\s*=|^class \w+\((db\.Model|Base|models\.Model)\b[^)]*\)"""
            r"""|^class \w+\(SQLModel,\s*table\s*=\s*True"""
        ),
        (".py",),
    ),
    (
        "mongoose",
        re.compile(r"""mongoose\.model\(|=\s*(new\s+)?(mongoose\.)?Schema\("""),
        (".js", ".ts"),
    ),
    ("gorm", re.compile(r"""gorm:"|func \(\w*\s*\*?\w+\) TableName\(\)"""), (".go",)),
    (
        "entity",
        re.compile(r"""@Entity\b|^model \w+ \{|@Table\("""),
        (".ts", ".java", ".kt", ".prisma"),
    ),
]


def dm_inventory(repo: RepoView) -> list[Item]:
    sites: list[Item] = []
    for f in repo.files():
        if TEST_RX.search(f):
            continue
        for kind, rx, exts in DM_RX:
            if not f.endswith(exts):
                continue
            last = -10
            for i, ln in enumerate(repo.lines(f) or [], 1):
                m = rx.search(ln)
                if m and not ln.strip().startswith(("--", "//", "#")):
                    if kind == "gorm" and i - last < 25:
                        last = i
                        continue
                    tbl = m.group(2) if kind == "ddl" else None
                    sites.append(
                        {
                            "file": f,
                            "line": i,
                            "text": ln.strip()[:160],
                            "kind": kind,
                            "table": (tbl or "").lower() or None,
                        }
                    )
                    last = i
    return sites


def block_len(repo: RepoView, site: Item) -> int:
    ls = repo.lines(site["file"]) or []
    for j in range(site["line"], min(len(ls), site["line"] + 300) + 1):
        if j > site["line"] and re.match(r"^\s*\)\s*[^,]*;?\s*$", ls[j - 1]):
            return j - site["line"]
    return 0


def dedupe_ddl(repo: RepoView, sites: list[Item]) -> dict[str, str]:
    """Same table created in several SQL files: keep the most complete definition as the
    obligation; the others stay valid citation sites but are pre-accounted as duplicates."""
    by: dict[str, list[Item]] = defaultdict(list)
    for s in sites:
        if s.get("table"):
            by[s["table"]].append(s)
    dup: dict[str, str] = {}
    for table, ss in by.items():
        if len(ss) > 1:
            keep = max(ss, key=lambda s: (block_len(repo, s), -len(s["file"])))
            for s in ss:
                if s is not keep:
                    dup[f"{s['file']}:{s['line']}"] = (
                        f"duplicate definition of table {table}; most complete definition at "
                        f"{keep['file']}:{keep['line']}"
                    )
    return dup


PERSIST_MARK_RX = re.compile(
    r"""gorm:"|db:"|bson:"|sql:"|TableName\(|__tablename__|Column\(|mapped_column"""
    r"""|Field\(.*primary_key|@Column|@Entity|@Table|Schema\("""
)
MODEL_DIR_RX = re.compile(r"(^|/)(entity|entities|model|models|domain|schemas?)(/|$)", re.I)
TYPE_RX = {
    ".go": re.compile(r"^type ([A-Z]\w*) struct\b"),
    ".py": re.compile(r"^class ([A-Z]\w*)\b"),
    ".ts": re.compile(r"^export (?:default )?(?:class|interface) ([A-Z]\w*)"),
    ".js": re.compile(r"^(?:export )?class ([A-Z]\w*)"),
    ".java": re.compile(r"^public (?:class|record) ([A-Z]\w*)"),
    ".kt": re.compile(r"^(?:data )?class ([A-Z]\w*)"),
}
STORE_RX = re.compile(
    r"(?i)postgres|mysql|mariadb|sqlite|mongo|redis|mssql|sqlserver|oracle|cassandra|dynamodb"
    r"|elasticsearch|clickhouse"
)


def has_persist_marker(repo: RepoView, t: Item, span: int = 40) -> bool:
    ls = repo.lines(t["file"]) or []
    return any(PERSIST_MARK_RX.search(ln) for ln in ls[t["line"] - 1 : t["line"] - 1 + span])


def model_type_inventory(repo: RepoView, cap: int = 40) -> list[Item]:
    out: list[Item] = []
    for f in repo.files():
        parent = f.rsplit("/", 1)[0] if "/" in f else ""
        if TEST_RX.search(f) or not MODEL_DIR_RX.search(parent):
            continue
        rx = next((r for e, r in TYPE_RX.items() if f.endswith(e)), None)
        if not rx:
            continue
        for i, ln in enumerate(repo.lines(f) or [], 1):
            if rx.match(ln):
                out.append({"file": f, "line": i, "text": ln.strip()[:160], "kind": "type"})
    return out[:cap]


def store_hints(repo: RepoView, cap: int = 14) -> list[str]:
    names = (
        "go.mod",
        "requirements.txt",
        "package.json",
        "pyproject.toml",
        "pom.xml",
        "build.gradle",
        "cargo.toml",
        "gemfile",
        "composer.json",
        ".env",
        ".env.example",
    )
    out: list[str] = []
    for f in repo.files():
        name = f.rsplit("/", 1)[-1].lower()
        if f.count("/") > 1 or not (
            name in names or "compose" in name or name.startswith("requirements")
        ):
            continue
        for i, ln in enumerate(repo.lines(f) or [], 1):
            if STORE_RX.search(ln):
                out.append(f"{f}:{i}: {ln.strip()[:120]}")
                if len(out) >= cap:
                    return out
    return out


def dm_outline(repo: RepoView, rel: str, starts: list[int], cap: int = 240) -> str:
    ls = repo.lines(rel) or []
    keep: set[int] = set()
    for s in starts:
        depth, end = 0, min(len(ls), s + 45)
        for j in range(s, end + 1):
            keep.add(j)
            t = ls[j - 1]
            depth += t.count("(") + t.count("{") - t.count(")") - t.count("}")
            if j > s and depth <= 0 and re.search(r"[)}];?\s*$|^\s*\)", t):
                break
    return f"== {rel} ({len(ls)} lines; definition blocks)\n" + _numbered(ls, keep, cap, 170)


def _numbered(ls: list[str], keep: set[int], cap: int, width: int) -> str:
    out: list[str] = []
    prev = 0
    for k in sorted(k for k in keep if 1 <= k <= len(ls))[:cap]:
        if prev and k != prev + 1:
            out.append("   ...")
        out.append(f"{k}: {ls[k - 1].rstrip()[:width]}")
        prev = k
    return "\n".join(out)


# ------------------------------------------------------------------ API candidate sites
VERBS = "GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS"
CALL_LIT = re.compile(
    r"""(@?[A-Za-z_$][\w$.]*)\s*\(\s*(?:[^()"'`]{0,60},\s*)?["'`]((?:"""
    + VERBS
    + r""")\s+)?(/[^"'`\s]*)["'`]"""
)
PREFIX_LIT = re.compile(
    r"""\b(\w*(?:prefix|Prefix|PREFIX|basePath|base_path|BasePath|mount|Mount)\w*)\s*[=:]\s*["'`](/[^"'`\s]*)["'`]"""
)
NOT_ROUTE_CALLS = re.compile(
    r"(?i)(^|\.)(sprintf|printf|println|print|errorf|fatalf|fatal|panicf?|hasprefix|hassuffix|"
    r"trimprefix|trimsuffix|contains|join|readfile|open|stat|getenv|startswith|endswith|replace|"
    r"split|log|info|warn|warning|debug|error|exists|mkdir|makedirs|remove|path|resolve|require|"
    r"import|include_str)$"
)
_SITE_DECL = re.compile(
    r"^\s*(func|def|async\s+def|class|type|interface|export|public|private|protected|"
    r"module\.exports|@\w)"
)
_TAG = re.compile(r"`[^`]*\b\w+:\"[^\"]*\"[^`]*`")
_VERB_TOKEN = re.compile(
    r"\b(" + VERBS + r"|Any|ANY)\b|\.(get|post|put|patch|delete|route|use|all)\s*\("
)
_SLASH_LIT = re.compile(r"""["'`](?:(?:""" + VERBS + r""")\s+)?/[A-Za-z0-9_:{}<>*.\-/]*["'`]""")
SITE_LITERAL = re.compile(r"""["'`](?:(?:""" + VERBS + r""")\s+)?(/[^"'`\s]*)["'`]""")


_EXTRA_SITE_SHAPE = re.compile(
    r"""["'`](?:/[^"'`\s]*|\*)["'`]"""
    r"|(?:^|[.\s@])(?:get|post|put|patch|delete|options|head|all|any|route|handle|handlefunc|"
    r"group|add_api_route|add_url_rule|add_resource|api_route|websocket)\s*\(",
    re.I,
)


def source_files(repo: RepoView) -> list[str]:
    return [f for f in repo.files() if is_src(f) and "/node_modules/" not in f]


def find_sites(repo: RepoView, extra_patterns: Iterable[str] = ()) -> dict[tuple[str, int], str]:
    """Candidate route-registration sites: {(file, line): text}. Noisy on purpose."""
    extra: list[re.Pattern[str]] = []
    for p in extra_patterns:
        try:
            extra.append(re.compile(p))
        except (re.error, TypeError):
            continue
    sites: dict[tuple[str, int], str] = {}
    for rel in source_files(repo):
        for i, ln in enumerate(repo.lines(rel) or [], 1):
            s = ln.strip()
            if s.startswith(("//", "#", "*", "/*")) or len(s) > 400:
                continue
            hit = False
            for m in CALL_LIT.finditer(ln):
                name = m.group(1).lstrip("@")
                if not NOT_ROUTE_CALLS.search(name.split(".")[-1]) and not NOT_ROUTE_CALLS.search(
                    name
                ):
                    hit = True
            if not hit and PREFIX_LIT.search(ln):
                hit = True
            if not hit and any(rx.search(ln) for rx in extra) and _EXTRA_SITE_SHAPE.search(ln):
                # a mechanism-proposed pattern only adds lines that look like a registration (a path
                # literal or an HTTP-verb call) — not middleware (app.use(helmet())) or bare braces
                hit = True
            if hit:
                sites[(rel, i)] = s[:200]
    return sites


def file_outline(repo: RepoView, rel: str, must_lines: Iterable[int] = (), cap: int = 260) -> str:
    """Compact line-numbered view: declarations, tags, route-like literals, verb tokens and the
    given lines (+-1)."""
    ls = repo.lines(rel) or []
    must = set(must_lines)
    keep = {
        i
        for i, ln in enumerate(ls, 1)
        if _SITE_DECL.match(ln)
        or _TAG.search(ln)
        or _SLASH_LIT.search(ln)
        or _VERB_TOKEN.search(ln)
    }
    for i in must:
        keep.update({i - 1, i, i + 1})
    ordered = sorted(k for k in keep if 1 <= k <= len(ls))
    if len(ordered) > cap:
        pri = [
            k
            for k in ordered
            if k in must or _SLASH_LIT.search(ls[k - 1]) or _TAG.search(ls[k - 1])
        ]
        rest = [k for k in ordered if k not in set(pri)]
        ordered = sorted(pri[:cap] + rest[: max(0, cap - len(pri))])
    return f"== {rel} ({len(ls)} lines; outline)\n" + _numbered(ls, set(ordered), cap, 180)


def plan_shards(
    repo: RepoView, files_with_lines: dict[str, list[int]], max_lines: int = 240
) -> list[list[tuple[str, str]]]:
    """Group files into shards whose outlines stay small."""
    items = []
    for rel, lines in sorted(files_with_lines.items()):
        o = file_outline(repo, rel, lines)
        items.append((rel, o, o.count("\n") + 1))
    shards: list[list[tuple[str, str]]] = []
    cur: list[tuple[str, str]] = []
    size = 0
    for rel, o, n in sorted(items, key=lambda x: (x[0].rsplit("/", 1)[0], x[0])):
        if cur and size + n > max_lines:
            shards.append(cur)
            cur, size = [], 0
        cur.append((rel, o))
        size += n
    if cur:
        shards.append(cur)
    return shards


def site_literals(text: str) -> set[str]:
    return {m.group(1).strip("/") for m in SITE_LITERAL.finditer(text or "")}


