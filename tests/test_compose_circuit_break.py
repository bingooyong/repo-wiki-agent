"""Circuit-break must stop new LLM page calls without waiting page timeouts.

Round 3 (FastAPI RealWorld, CLI a3d58b4): 16×529 then
``provider_disabled_after_failures=true``, but all 89 compose jobs were
submitted to ``asyncio.gather`` first, so remaining pages could not skip
LLM and became extra fallbacks (2 → 26). Empty-content retry (#42) and
HTTP 5xx/429 retry (#40) stay covered in ``test_llm_compose_retry.py``.
"""

from __future__ import annotations

import asyncio
import time
from pathlib import Path

import pytest

from repo_wiki.core.config import RepoWikiConfig
from repo_wiki.core.contracts import RepositoryInfo, RepositorySnapshot
from repo_wiki.llm.config import LLMProviderConfig
from repo_wiki.llm.models import (
    ChatRequest,
    ChatResponse,
    ErrorCode,
    LLMProvider,
    ProviderCapabilities,
    RetryableError,
)
from repo_wiki.orchestration.service import RepoWikiService
from repo_wiki.planner.schema import WikiPagePlan, WikiPlanManifest, WikiTaxonomyCategory

PAGE_COUNT = 8
MAX_FAILURES = 2
CONCURRENCY = 2
PAGE_TIMEOUT_SECONDS = 1.5
SUCCESS_MARKDOWN = """# Sample Page

## 简介

This page was generated by a fake provider for circuit-break scheduler tests.
It includes enough prose so the composer keeps the page instead of rejecting
it for insufficient content. Healthy providers must still compose every page.

## 项目结构

The repository layout is described here with extra padding sentences so
validation passes without falling back to templates during the success path.
"""


def _retryable_529() -> RetryableError:
    return RetryableError(
        message="Server error: 529",
        code=ErrorCode.SERVER_ERROR,
        details={"status": 529},
    )


def _success_response() -> ChatResponse:
    return ChatResponse(content=SUCCESS_MARKDOWN, model="mock-gpt")


class CircuitBreak529Provider(LLMProvider):
    """Immediate 529 for a budget of calls, then hang (cancelled by page timeout).

    Fail-fast calls wait until ``fail_fast_limit`` chats are in flight so the
    scheduler race (admit a third job before the second failure is recorded)
    is deterministic under pytest-asyncio.
    """

    def __init__(self, fail_fast_limit: int) -> None:
        self._fail_fast_limit = fail_fast_limit
        self._call_count = 0
        self._hang_count = 0
        self._fail_fast_started = 0
        self._fail_fast_gate = asyncio.Event()
        self._config = LLMProviderConfig(
            provider="mock",
            model="mock-gpt",
            timeout=PAGE_TIMEOUT_SECONDS,
            max_retries=0,
        )

    @property
    def name(self) -> str:
        return "circuit-break-529-fake"

    @property
    def capabilities(self) -> ProviderCapabilities:
        return ProviderCapabilities()

    @property
    def call_count(self) -> int:
        return self._call_count

    @property
    def hang_count(self) -> int:
        return self._hang_count

    async def chat(self, request: ChatRequest) -> ChatResponse:
        self._call_count += 1
        if self._call_count <= self._fail_fast_limit:
            self._fail_fast_started += 1
            if self._fail_fast_started >= self._fail_fast_limit:
                self._fail_fast_gate.set()
            await self._fail_fast_gate.wait()
            raise _retryable_529()
        self._hang_count += 1
        await request_never_returns()
        raise AssertionError("hang path must be cancelled, not return")

    def validate_config(self) -> list[tuple[str, str | None, str]]:
        return []


class HealthyLLMProvider(LLMProvider):
    """Always returns composable Markdown; never hangs or 529s."""

    def __init__(self) -> None:
        self._call_count = 0
        self._config = LLMProviderConfig(
            provider="mock",
            model="mock-gpt",
            timeout=PAGE_TIMEOUT_SECONDS,
            max_retries=0,
        )

    @property
    def name(self) -> str:
        return "healthy-fake"

    @property
    def capabilities(self) -> ProviderCapabilities:
        return ProviderCapabilities()

    @property
    def call_count(self) -> int:
        return self._call_count

    async def chat(self, request: ChatRequest) -> ChatResponse:
        self._call_count += 1
        return _success_response()

    def validate_config(self) -> list[tuple[str, str | None, str]]:
        return []


class Single529ThenHealthyProvider(LLMProvider):
    """First chat is 529; later chats succeed. Must not trip the failure budget."""

    def __init__(self) -> None:
        self._call_count = 0
        self._config = LLMProviderConfig(
            provider="mock",
            model="mock-gpt",
            timeout=PAGE_TIMEOUT_SECONDS,
            max_retries=0,
        )

    @property
    def name(self) -> str:
        return "single-529-fake"

    @property
    def capabilities(self) -> ProviderCapabilities:
        return ProviderCapabilities()

    @property
    def call_count(self) -> int:
        return self._call_count

    async def chat(self, request: ChatRequest) -> ChatResponse:
        self._call_count += 1
        if self._call_count == 1:
            raise _retryable_529()
        return _success_response()

    def validate_config(self) -> list[tuple[str, str | None, str]]:
        return []


async def request_never_returns() -> None:
    """Park until the page ``wait_for`` timeout cancels the task."""
    await asyncio.Event().wait()


def _plan(n: int = PAGE_COUNT) -> WikiPlanManifest:
    pages = [
        WikiPagePlan(
            page_id=f"page-{idx:02d}",
            title=f"Sample Page {idx:02d}",
            category=WikiTaxonomyCategory.PROJECT_OVERVIEW,
            output_path=f"docs/page-{idx:02d}.md",
        )
        for idx in range(n)
    ]
    return WikiPlanManifest(pages=pages)


def _snapshot(root: Path) -> RepositorySnapshot:
    return RepositorySnapshot(
        repository=RepositoryInfo(
            name="circuit-break-test",
            root_path=str(root),
            language="python",
            framework="pytest",
        )
    )


def _service(root: Path) -> RepoWikiService:
    config = RepoWikiConfig.model_validate(
        {
            "project": {"name": "circuit-break-test", "root": str(root)},
            "llm": {
                "force_mock_llm": True,
                "max_concurrent": CONCURRENCY,
                "timeout": PAGE_TIMEOUT_SECONDS,
                "max_retries": 0,
            },
        }
    )
    return RepoWikiService(config)


def _summary(provider: LLMProvider, config: LLMProviderConfig) -> dict[str, object]:
    return {
        "effective_provider": provider.name,
        "model": config.model,
        "mode": "real",
        "mock_reason": None,
        "fallback_warning": None,
    }


def _install_provider(
    monkeypatch: pytest.MonkeyPatch,
    service: RepoWikiService,
    provider: LLMProvider,
) -> LLMProviderConfig:
    config = provider._config  # type: ignore[attr-defined]
    monkeypatch.setattr(
        service,
        "_resolve_qoder_like_llm",
        lambda: (provider, config, _summary(provider, config)),
    )
    return config


