@pytest.mark.asyncio
async def test_circuit_break_skips_remaining_pages_without_timeout_wait(
    compose_env: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    root = compose_env / "repo"
    root.mkdir()
    output_dir = compose_env / "run"
    output_dir.mkdir()
    provider = CircuitBreak529Provider(fail_fast_limit=MAX_FAILURES)
    service = _service(root)
    _install_provider(monkeypatch, service, provider)

    started = time.perf_counter()
    result = await service._compose_qoder_like_pages(
        plan=_plan(),
        evidence_bindings={},
        snapshot=_snapshot(root),
        output_dir=output_dir,
    )
    elapsed = time.perf_counter() - started
    llm = result["llm"]

    # Scheduling test, not a micro-benchmark. CI 3.11 observed 1.53s vs a
    # 1.5s cap. The pre-fix gather queued every leftover page, so remaining
    # work waited ceil((8-2)/2) timeout waves (~4.5s). 3s is above one
    # timeout of jitter and still below that gather wait. hang_count==0 is
    # the proof leftover pages never entered the per-page timeout path.
    assert elapsed < 3.0
    assert provider.hang_count == 0
    assert provider.call_count == MAX_FAILURES
    assert provider.call_count < PAGE_COUNT
    assert llm["provider_disabled_after_failures"] is True
    assert llm["fallback_page_count"] == PAGE_COUNT
    assert llm["llm_call_count"] == provider.call_count
    assert llm["llm_call_count"] < PAGE_COUNT
    fallback_modes = {meta["generation_mode"] for meta in result["page_metadata"]}
    assert fallback_modes == {"fallback"}
    disabled_reasons = [
        reason
        for meta in result["page_metadata"]
        for reason in meta["reasons"]
        if "provider disabled after" in reason
    ]
    assert disabled_reasons


@pytest.mark.asyncio
async def test_healthy_provider_composes_all_pages(
    compose_env: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    root = compose_env / "repo"
    root.mkdir()
    output_dir = compose_env / "run"
    output_dir.mkdir()
    provider = HealthyLLMProvider()
    service = _service(root)
    _install_provider(monkeypatch, service, provider)

    result = await service._compose_qoder_like_pages(
        plan=_plan(),
        evidence_bindings={},
        snapshot=_snapshot(root),
        output_dir=output_dir,
    )
    llm = result["llm"]

    assert provider.call_count == PAGE_COUNT
    assert llm["llm_call_count"] == PAGE_COUNT
    assert llm["fallback_page_count"] == 0
    assert llm["provider_disabled_after_failures"] is False
    assert {meta["generation_mode"] for meta in result["page_metadata"]} == {"llm"}
    assert len(result["pages"]) == PAGE_COUNT
    assert all(markdown for _path, markdown in result["pages"])


@pytest.mark.asyncio
async def test_single_529_does_not_disable_provider(
    compose_env: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    root = compose_env / "repo"
    root.mkdir()
    output_dir = compose_env / "run"
    output_dir.mkdir()
    provider = Single529ThenHealthyProvider()
    service = _service(root)
    _install_provider(monkeypatch, service, provider)

    result = await service._compose_qoder_like_pages(
        plan=_plan(),
        evidence_bindings={},
        snapshot=_snapshot(root),
        output_dir=output_dir,
    )
    llm = result["llm"]
    modes = [meta["generation_mode"] for meta in result["page_metadata"]]

    assert llm["provider_disabled_after_failures"] is False
    assert llm["fallback_page_count"] == 1
    assert modes.count("fallback") == 1
    assert modes.count("llm") == PAGE_COUNT - 1
    assert provider.call_count == PAGE_COUNT
