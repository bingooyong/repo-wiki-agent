COMPOSED = pad_handbook_markdown(
    "# Sample Page\n\n## 简介\n\nThis page was generated by a fake composer provider for the agent-loop "
    "service tests. It has enough prose to be kept by the composer.\n"
)


class HealthyProvider(LLMProvider):
    def __init__(self) -> None:
        self.calls: list[str] = []
        self._config = LLMProviderConfig(
            provider="mock", model="mock-gpt", timeout=5, max_retries=0
        )

    @property
    def name(self) -> str:
        return "healthy-fake"

    @property
    def capabilities(self) -> ProviderCapabilities:
        return ProviderCapabilities()

    async def chat(self, request: ChatRequest) -> ChatResponse:
        self.calls.append("chat")
        return ChatResponse(content=COMPOSED, model="mock-gpt")

    def validate_config(self) -> list[tuple[str, str | None, str]]:
        return []


def _plan() -> WikiPlanManifest:
    pages = [
        WikiPagePlan(
            page_id="project-overview",
            title="项目概览",
            category=WikiTaxonomyCategory.PROJECT_OVERVIEW,
            output_path="docs/project-overview.md",
        ),
        WikiPagePlan(
            page_id="api-overview",
            title="API 参考",
            category=WikiTaxonomyCategory.API_REFERENCE,
            output_path="docs/api-overview.md",
        ),
        WikiPagePlan(
            page_id="other-page",
            title="Other Page",
            category=WikiTaxonomyCategory.PROJECT_OVERVIEW,
            output_path="docs/other-page.md",
        ),
    ]
    return WikiPlanManifest(pages=pages)


def _service(root: Path, enabled: bool) -> tuple[RepoWikiService, HealthyProvider]:
    config = RepoWikiConfig.model_validate(
        {
            "project": {"name": "demo-shop", "root": str(root)},
            "llm": {"force_mock_llm": True, "max_retries": 0},
            "agent_loop": {"enabled": enabled, "max_iters": 1, "page_types": ["overview", "api"]},
        }
    )
    service = RepoWikiService(config)
    provider = HealthyProvider()
    cfg = provider._config
    service._resolve_qoder_like_llm = lambda: (  # type: ignore[method-assign]
        provider,
        cfg,
        {"effective_provider": provider.name, "model": cfg.model, "mode": "real"},
    )
    return service, provider


@pytest.fixture
def env(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> Path:
    monkeypatch.delenv("REPO_WIKI_AGENT_LOOP", raising=False)
    monkeypatch.setenv("REPO_WIKI_LLM_PRIORITY", "plan")
    monkeypatch.setenv("REPO_WIKI_COMPOSER_CACHE_PATH", str(tmp_path / "composer-cache.sqlite3"))
    make_demo_repo(tmp_path / "repo")
    (tmp_path / "run").mkdir()
    return tmp_path


def _scripted(monkeypatch: pytest.MonkeyPatch, model: Any) -> None:
    monkeypatch.setattr(
        "repo_wiki.agent_loop.orchestrator.OpenAICompatibleClient",
        lambda *a, **k: ScriptedClient(model),
    )


async def _compose(service: RepoWikiService, root: Path, out: Path) -> dict[str, Any]:
    snapshot = RepositorySnapshot(
        repository=RepositoryInfo(
            name="demo-shop", root_path=str(root), language="python", framework="flask"
        )
    )
    return await service._compose_qoder_like_pages(
        plan=_plan(), evidence_bindings={}, snapshot=snapshot, output_dir=out
    )


@pytest.mark.asyncio
async def test_disabled_by_default_keeps_every_page_on_the_composer(
    env: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    def boom(*a: Any, **k: Any) -> None:
        raise AssertionError("agent loop must not run when disabled")

    monkeypatch.setattr("repo_wiki.agent_loop.orchestrator.AgentLoopOrchestrator.__init__", boom)
    service, provider = _service(env / "repo", enabled=False)
    result = await _compose(service, env / "repo", env / "run")
    modes = {m["page_id"]: m["generation_mode"] for m in result["page_metadata"]}
    assert set(modes) == {"project-overview", "api-overview", "other-page"}
    assert "agent_loop" not in modes.values()
    assert len(provider.calls) == 3
    assert "agent_loop" not in result["llm"]


@pytest.mark.asyncio
async def test_enabled_routes_mapped_pages_through_the_agent_loop(
    env: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _scripted(monkeypatch, ScriptedModel(demo_rules()))
    service, provider = _service(env / "repo", enabled=True)
    result = await _compose(service, env / "repo", env / "run")
    meta = {m["page_id"]: m for m in result["page_metadata"]}
    assert meta["project-overview"]["generation_mode"] == "agent_loop"
    assert meta["project-overview"]["quality_state"] == "READY"
    assert meta["api-overview"]["generation_mode"] == "agent_loop"
    assert meta["other-page"]["generation_mode"] != "agent_loop"
    assert len(provider.calls) == 1  # only the unmapped page used the composer
    pages = dict(result["pages"])
    report = (env / "run" / "agent-loop" / "page-overview.md").read_text()
    assert pages["docs/project-overview.md"] == report  # shipped verbatim, no composer post-pass
    assert "## 架构图" not in pages["docs/project-overview.md"]
    assert result["llm"]["agent_loop"]["pages"]["api-overview"]["status"] == "pass"
    assert (env / "repo" / ".repo-wiki" / "agent-loop" / "cassette" / "cassette.jsonl").exists()


@pytest.mark.asyncio
async def test_failed_agent_loop_page_is_dropped_not_shipped(
    env: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    junk = "<minimax:tool_call>x</minimax:tool_call>"
    _scripted(monkeypatch, ScriptedModel(demo_rules(overview_writer=junk)))
    service, _provider = _service(env / "repo", enabled=True)
    result = await _compose(service, env / "repo", env / "run")
    meta = {m["page_id"]: m for m in result["page_metadata"]}
    assert meta["project-overview"]["quality_state"] == "DROPPED"
    assert meta["project-overview"]["reasons"][0].startswith("agent_loop_failed")
    assert "docs/project-overview.md" not in dict(result["pages"])
    assert meta["api-overview"]["generation_mode"] == "agent_loop"
    dropped = [f["page_id"] for f in result["failed_pages"]]
    assert dropped == ["project-overview"]


@pytest.mark.asyncio
async def test_env_switch_can_force_the_loop_off(
    env: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setenv("REPO_WIKI_AGENT_LOOP", "0")
    service, provider = _service(env / "repo", enabled=True)
    result = await _compose(service, env / "repo", env / "run")
    assert "agent_loop" not in {m["generation_mode"] for m in result["page_metadata"]}
    assert len(provider.calls) == 3
